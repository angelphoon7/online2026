// Generate the subgraph's network bindings from the deployment record.
//
//   node scripts/gen-subgraph-config.mjs [network]
//
// Writes:
//   subgraph/networks.json   consumed by `graph build --network <network>`; its keys must
//                            match the dataSource `name` fields in subgraph.yaml exactly,
//                            because that is how graph-cli substitutes address and startBlock.
//   subgraph/src/config.ts   address constants for the mapping handlers (custody is derived
//                            by comparing Transfer participants against the Escrow address).
//
// Both are generated. deployments/<network>.json stays the single source of truth; nothing
// here is hand-written, so a redeploy cannot leave a stale address behind.

import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { loadDeployment, deploymentName, CONTRACT_NAMES } from './lib/deployment.mjs';

// TicketNFT, IntentRegistry and Settlement are dataSources. Escrow is not indexed as its own
// dataSource: custody is derivable from ERC-721 Transfer (see docs/graph-audit.txt C3/note 7),
// but its address is still needed by the handlers to recognise those transfers.
export const DATA_SOURCES = ['TicketNFT', 'IntentRegistry', 'Settlement'];

export function networksJson(deployment) {
  const entries = DATA_SOURCES.map((name) => [
    name,
    {
      address: deployment.contracts[name].address,
      startBlock: deployment.contracts[name].startBlock,
    },
  ]);
  return { [deployment.network]: Object.fromEntries(entries) };
}

export function configTs(deployment) {
  const constant = (name, address) =>
    `export const ${name} = Address.fromString("${address}");`;
  return [
    '// GENERATED by scripts/gen-subgraph-config.mjs — do not edit by hand.',
    `// Source: ${deployment.file} (network ${deployment.network}, chainId ${deployment.chainId})`,
    '',
    'import { Address } from "@graphprotocol/graph-ts";',
    '',
    ...CONTRACT_NAMES.map((name) =>
      constant(name.replace(/([a-z])([A-Z])/g, '$1_$2').toUpperCase(), deployment.contracts[name].address)
    ),
    constant('USDC', deployment.usdc),
    '',
    `export const CHAIN_ID = ${deployment.chainId};`,
    '',
  ].join('\n');
}

export const serialiseNetworks = (value) => JSON.stringify(value, null, 2) + '\n';

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const network = deploymentName(process.argv.slice(2).find((a) => !a.startsWith('--')));
  const deployment = loadDeployment(network);

  fs.mkdirSync(path.join('subgraph', 'src'), { recursive: true });
  fs.writeFileSync(path.join('subgraph', 'networks.json'), serialiseNetworks(networksJson(deployment)));
  fs.writeFileSync(path.join('subgraph', 'src', 'config.ts'), configTs(deployment));

  console.log(`networks.json + src/config.ts written for ${network}`);
  for (const name of DATA_SOURCES) {
    const { address, startBlock } = deployment.contracts[name];
    console.log(`  ${name.padEnd(15)} ${address}  startBlock ${startBlock}`);
  }
  console.log(`  (Escrow ${deployment.contracts.Escrow.address} — constant only, not a dataSource)`);
}
